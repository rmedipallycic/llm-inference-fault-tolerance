"""Phase 3 (gateway) tables for the paper, from the committed gateway runs.

Called by analysis/make_tables.py; writes into paper/tables/:

  gw_restart.tex   restart recovery through the gateway, one row per run
  gw_failover.tex  failover to a replica on a second machine, one row per run
  gw_overhead.tex  failure-free cost of the gateway, one row per run
  gw_macros.tex    in-text numbers for the gateway sections

Delivery is recomputed from the events each client recorded (gateway/check.py),
not taken from the trial files. "Same text" means the client's final text
equals one of the run's two failure-free references. Run conditions that the
records cannot capture (how the second machine was prepared) come from
experiments/run_conditions.json.
"""
import glob
import json
import os
import statistics
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from gateway.check import delivery, text_of  # noqa: E402

ENGINE = {"vllm": "vLLM", "sglang": "SGLang"}
MODE = {"default": "default", "batch-invariant": "batch-inv.", "deterministic": "determ."}
HEADER = "% generated by analysis/make_tables.py (analysis/gw_tables.py); do not edit by hand\n"


sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gw_timing  # noqa: E402


def frac(k, n):
    return f"{k}/{n}" if n else "--"


def num(x, fmt):
    return fmt.format(x).replace("-", "$-$")


def med_range(xs, fmt="{:.2f}"):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "--"
    return f"{num(statistics.median(xs), fmt)} ({num(min(xs), fmt)}--{num(max(xs), fmt)})"


def lcp(a, b):
    n, i = min(len(a), len(b)), 0
    while i < n and a[i] == b[i]:
        i += 1
    return i


def condition_short(text):
    if not text:
        return "--"
    cache = "shared cache" if "machine 1's compile caches" in text else "own cache"
    pk = "identical packages" if "packages identical" in text else "packages differ"
    return f"{cache}, {pk}"


def engine_mode(run):
    env = run["environment"].get("engine_env") or {}
    if env.get("VLLM_BATCH_INVARIANT") == "1":
        return "batch-invariant"
    if "--enable-deterministic-inference" in (run["config"].get("server_cmd") or ""):
        return "deterministic"
    return "default"


def load(root):
    conds = {}
    path = os.path.join(root, "run_conditions.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            conds = {k: v for k, v in json.load(f).items() if not k.startswith("_")}
    kills, overheads = [], []
    for run_path in sorted(glob.glob(os.path.join(root, "*_gw_*", "run.json"))):
        with open(run_path, encoding="utf-8") as f:
            run = json.load(f)
        if run.get("run_type") != "measured":
            continue
        d, cfg = os.path.dirname(run_path), run["config"]
        r = {"dir": d, "run_id": run["run_id"], "engine": run["engine"], "mode": engine_mode(run),
             "T": float(cfg["temperature"]), "fsync": bool(cfg.get("fsync")),
             "remote": bool(run.get("remote_backends")), "cond": conds.get(run["run_id"]),
             "run": run}
        if cfg.get("kill_at") is None:
            with open(os.path.join(d, "overhead.json"), encoding="utf-8") as f:
                r["pairs"] = json.load(f)
            overheads.append(r)
            continue
        refs = {run["reference"]["text"], run["reference_repeat"]["text"]}
        r["kill"], r["trials"] = int(cfg["kill_at"]), []
        for tp in sorted(glob.glob(os.path.join(d, "trial_*.json"))):
            with open(tp, encoding="utf-8") as f:
                t = json.load(f)
            ev = t["client"]["events"]
            log = gw_timing.entries(d, t["client"].get("req_id"))
            rec_gw = gw_timing.recovery_s(log, t.get("t_kill"))
            r["trials"].append({"d": delivery(ev), "same": text_of(ev) in refs,
                                "complete": t["client"].get("finish_reason") in ("length", "stop"),
                                # recovery from the gateway's log (analysis/gw_timing.py);
                                # the client-side figure is kept as rec_client
                                "rec": rec_gw if rec_gw is not None else t.get("recovery_latency_s"),
                                "rec_client": t.get("recovery_latency_s")})
        kills.append(r)
    return kills, overheads


def exactly_once(ts):
    return sum(t["d"]["exactly_once"] and t["complete"] for t in ts)


def timing(t0, times):
    """ms to first token, ms per token after the first, s end to end."""
    return ((times[0] - t0) * 1000, (times[-1] - times[0]) / (len(times) - 1) * 1000,
            times[-1] - t0)


def write(root, out):
    kills, overheads = load(root)
    if not kills:
        return None
    restart = sorted((r for r in kills if not r["remote"]),
                     key=lambda r: (r["engine"] != "vllm", r["mode"] != "default", r["T"], r["kill"]))
    failover = sorted((r for r in kills if r["remote"]), key=lambda r: r["run_id"])

    with open(os.path.join(out, "gw_restart.tex"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for r in restart:
            ts = r["trials"]
            f.write(f"{ENGINE[r['engine']]} & {MODE[r['mode']]} & {r['T']:g} & {r['kill']} & "
                    f"{frac(exactly_once(ts), len(ts))} & {frac(sum(t['same'] for t in ts), len(ts))} & "
                    f"{med_range([t['rec'] for t in ts], '{:.1f}')} \\\\\n")

    with open(os.path.join(out, "gw_failover.tex"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for r in failover:
            ts = r["trials"]
            f.write(f"{MODE[r['mode']]} & {r['T']:g} & {condition_short(r['cond'])} & "
                    f"{frac(exactly_once(ts), len(ts))} & {frac(sum(t['same'] for t in ts), len(ts))} & "
                    f"{med_range([t['rec'] for t in ts])} \\\\\n")

    with open(os.path.join(out, "gw_overhead.tex"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for r in sorted(overheads, key=lambda r: (r["engine"] != "vllm", r["fsync"])):
            dd = [timing(p["direct"]["t_start_mono"], [c["t_mono"] for c in p["direct"]["chunks"]])
                  for p in r["pairs"]]
            gg = []
            for p in r["pairs"]:
                g = p["gateway"]
                log = gw_timing.entries(r["dir"], g.get("req_id"))
                ttft, tpot = gw_timing.ttft_s(log, g), gw_timing.tpot_s(log)
                client = timing(g["t_start_mono"], [e["t_mono"] for e in g["events"]])
                # first token and per-token time from the gateway's log; end to end
                # from the client (the last event is flushed when the stream closes)
                gg.append((ttft * 1000 if ttft is not None else client[0],
                           tpot * 1000 if tpot is not None else client[1], client[2]))
            cols = []
            for i, fmt in ((0, "{:.1f}"), (1, "{:.2f}"), (2, "{:.2f}")):
                diff = statistics.median(y[i] - x[i] for x, y in zip(dd, gg))
                cols.append(f"{num(statistics.median(x[i] for x in dd), fmt)} & "
                            f"{num(statistics.median(x[i] for x in gg), fmt)} & "
                            f"{'+' if diff >= 0 else ''}{num(diff, fmt)}")
            f.write(f"{ENGINE[r['engine']]} & {'yes' if r['fsync'] else 'no'} & {len(r['pairs'])} & "
                    + " & ".join(cols) + " \\\\\n")

    # in-text numbers
    allt = [t for r in kills for t in r["trials"]]

    def same(rs):
        ts = [t for r in rs for t in r["trials"]]
        return f"{sum(t['same'] for t in ts)}/{len(ts)}"

    def run_median(r):
        return statistics.median(t["rec"] for t in r["trials"] if t["rec"] is not None)

    m = {"GwKillTrials": len(allt), "GwExactlyOnce": exactly_once(allt),
         "GwDupPositions": sum(t["d"]["duplicated_positions"] for t in allt),
         "GwMissingPositions": sum(t["d"]["missing_positions"] for t in allt),
         "GwVllmTrials": sum(len(r["trials"]) for r in kills if r["engine"] == "vllm"),
         "GwSglangTrials": sum(len(r["trials"]) for r in kills if r["engine"] == "sglang"),
         "GwRestartTrials": sum(len(r["trials"]) for r in restart),
         "GwFailoverTrials": sum(len(r["trials"]) for r in failover)}
    for eng, key in (("vllm", "Vllm"), ("sglang", "Sglang")):
        rr = [r for r in restart if r["engine"] == eng]
        meds = [run_median(r) for r in rr if r["mode"] == "default"]
        m[f"GwRestartMin{key}"] = f"{min(meds):.0f}"
        m[f"GwRestartMax{key}"] = f"{max(meds):.0f}"
        m[f"GwDetSame{key}"] = same([r for r in rr if r["mode"] != "default"])
        m[f"GwDefaultZeroSame{key}"] = same([r for r in rr if r["mode"] == "default" and r["T"] == 0])
        m[f"GwDefaultHotSame{key}"] = same([r for r in rr if r["mode"] == "default" and r["T"] > 0])
    fmeds = [run_median(r) for r in failover]
    m["GwFailoverMin"], m["GwFailoverMax"] = f"{min(fmeds):.2f}", f"{max(fmeds):.2f}"
    cmeds = [statistics.median(t["rec_client"] for t in r["trials"] if t["rec_client"] is not None)
             for r in failover]
    m["GwFailoverClientMin"], m["GwFailoverClientMax"] = f"{min(cmeds):.2f}", f"{max(cmeds):.2f}"
    own = [r for r in failover if r["mode"] == "batch-invariant" and "own" in condition_short(r["cond"])]
    shared = [r for r in failover if r["mode"] == "batch-invariant" and "shared" in condition_short(r["cond"])]
    m["GwOwnCacheSame"], m["GwSharedCacheSame"] = same(own), same(shared)

    def remote_ref(r):
        return list(r["run"]["remote_reference"].values())[0]["text"]
    m["GwSplitChar"] = "/".join(str(x) for x in sorted({lcp(r["run"]["reference"]["text"], remote_ref(r))
                                                       for r in own}))
    m["GwSharedRefsEqual"] = "yes" if all(r["run"]["reference"]["text"] == remote_ref(r)
                                          for r in shared) else "no"
    with open(os.path.join(out, "gw_macros.tex"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for k, v in m.items():
            f.write("\\newcommand{\\" + k + "}{" + str(v) + "}\n")
    return m
