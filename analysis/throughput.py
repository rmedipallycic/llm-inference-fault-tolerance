"""Summarize the throughput runs (harness/run_throughput.py) from raw records.

  python analysis/throughput.py --out experiments/throughput_summary.md

Per run and concurrency level:
  tok/s     output tokens / wall time of the level (first request sent to
            last request finished); tokens from the engine's usage report,
            or the chunk count if it sent none
  vs default  tok/s relative to the mean of the engine's "default" runs
            at the same level
  TTFT      time to first token, ms, median over the level's requests
  TPOT      time per output token after the first, ms, median
  outputs   distinct temperature-0 texts per prompt across the WHOLE run
            (all levels), max over the six prompts; 1 means every request
            for every prompt got the same text
"""
import argparse
import glob
import json
import os
import statistics


def tokens(r):
    u = r.get("usage") or {}
    return u.get("completion_tokens") or len(r["chunks"])


def load(root):
    runs = []
    for path in sorted(glob.glob(os.path.join(root, "*_tput_*", "run.json"))):
        with open(path, encoding="utf-8") as f:
            run = json.load(f)
        if run.get("run_type") != "measured":
            continue
        req = os.path.join(os.path.dirname(path), "requests.jsonl")
        if not os.path.exists(req):
            continue
        with open(req, encoding="utf-8") as f:
            run["records"] = [json.loads(line) for line in f if line.strip()]
        runs.append(run)
    return runs


def summarize(run):
    rows = []
    texts = {}
    for r in run["records"]:
        if not r["error"]:
            texts.setdefault(r["prompt_id"], set()).add("".join(c["text"] for c in r["chunks"]))
    distinct = max((len(v) for v in texts.values()), default=0)
    for w in run["level_windows"]:
        rs = [r for r in run["records"] if r["level"] == w["level"]]
        ok = [r for r in rs if not r["error"] and len(r["chunks"]) >= 2]
        wall = w["t_end_mono"] - w["t_start_mono"]
        toks = sum(tokens(r) for r in ok)
        ttft = [(r["chunks"][0]["t_mono"] - r["t_start_mono"]) * 1000 for r in ok]
        tpot = [(r["chunks"][-1]["t_mono"] - r["chunks"][0]["t_mono"])
                / max(tokens(r) - 1, 1) * 1000 for r in ok]
        rows.append({"level": w["level"], "requests": len(rs), "errors": len(rs) - len(ok),
                     "tps": toks / wall if wall > 0 else 0.0,
                     "ttft": statistics.median(ttft) if ttft else None,
                     "tpot": statistics.median(tpot) if tpot else None})
    return rows, distinct


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--root", default="experiments")
    p.add_argument("--out", default=None)
    a = p.parse_args()
    runs = load(a.root)
    summ = {r["run_id"]: summarize(r) for r in runs}
    base = {}        # mean tok/s of the engine's "default" runs, per level
    for r in runs:
        if r["label"] == "default":
            for x in summ[r["run_id"]][0]:
                base.setdefault(r["engine"], {}).setdefault(x["level"], []).append(x["tps"])
    base = {e: {lv: statistics.mean(v) for lv, v in d.items()} for e, d in base.items()}
    lines = ["## Throughput of the anomaly fixes", "",
             "Generated by `analysis/throughput.py` from `experiments/*_tput_*`.", "",
             "| run_id | engine | config | T | C | requests | errors | tok/s | vs default "
             "| TTFT ms | TPOT ms | outputs per prompt | git_commit |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        rows, distinct = summ[r["run_id"]]
        for x in rows:
            b = base.get(r["engine"], {}).get(x["level"])
            rel = f"{x['tps'] / b:.2f}x" if b else "-"
            f = (lambda v, s: s.format(v) if v is not None else "-")
            lines.append(
                f"| {r['run_id']} | {r['engine']} | {r['label']} | {r['config']['temperature']} "
                f"| {x['level']} | {x['requests']} | {x['errors']} | {x['tps']:.0f} | {rel} "
                f"| {f(x['ttft'], '{:.0f}')} | {f(x['tpot'], '{:.1f}')} | {distinct} "
                f"| {(r['environment'].get('git_commit') or '')[:7]} |")
    text = "\n".join(lines) + "\n"
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
