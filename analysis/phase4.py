"""Phase 4 (RQ3) summary from raw records: recompute (prefill) cost and KV copy
cost against context length, and where, if anywhere, they cross.

  python analysis/phase4.py --out experiments/phase4_summary.md

Recompute: median time to first token for an L-token prompt with max_tokens=1
(harness/run_prefill.py), i.e. the prefill a recompute recovery pays. A request
whose single token decoded to empty text has no chunk; its end time is used
and counted in the "no text" column.
Copy: median times from harness/kv_copy_bench.py. "restore from host" is h2d;
"restore from disk" is disk_read + h2d. The ratio columns are recompute time
divided by restore time: above 1 means restoring a saved KV cache would have been
faster than recomputing it, for that path, before any checkpointing overhead.
"""
import argparse
import glob
import json
import os
import statistics


def load(root, pattern, recfile):
    runs = []
    for path in sorted(glob.glob(os.path.join(root, pattern, "run.json"))):
        with open(path, encoding="utf-8") as f:
            run = json.load(f)
        if run.get("run_type") != "measured":
            continue
        rp = os.path.join(os.path.dirname(path), recfile)
        if os.path.exists(rp):
            with open(rp, encoding="utf-8") as f:
                run["records"] = [json.loads(x) for x in f if x.strip()]
            runs.append(run)
    return runs


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def fmt(x, s="{:.3f}"):
    return s.format(x) if x is not None else "-"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--root", default="experiments")
    p.add_argument("--out", default=None)
    a = p.parse_args()
    pre = load(a.root, "*_prefill_*", "requests.jsonl")
    cop = load(a.root, "*_kvcopy", "records.jsonl")

    lines = ["## Phase 4: recompute versus KV copy", "",
             "Generated by `analysis/phase4.py` from `experiments/*_prefill_*` and `*_kvcopy`.", ""]
    recompute = {}
    lines += ["### Recompute (prefill to first token)", "",
              "| run_id | engine | config | L | ok | no text (end time used) | TTFT median s | min | max | tokens/s |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for r in pre:
        for L in r["lengths"]:
            rs = [x for x in r["records"] if x["length"] == L]
            # With max_tokens=1 the only token can decode to empty text (part of a
            # multi-byte character), so no chunk is recorded; the request's end is
            # then the first-token time (the stream closes right after the token).
            ok = [(x["t_first_mono"] or x["t_end_mono"]) - x["t_start_mono"] for x in rs
                  if not x["error"]]
            no_text = sum(1 for x in rs if not x["error"] and not x["t_first_mono"])
            m = med(ok)
            recompute.setdefault(L, []).append(m)
            lines.append(f"| {r['run_id']} | {r['engine']} | {r['label']} | {L} | {len(ok)}/{len(rs)} | {no_text} "
                         f"| {fmt(m)} | {fmt(min(ok) if ok else None)} | {fmt(max(ok) if ok else None)} "
                         f"| {fmt(L / m if m else None, '{:.0f}')} |")
    copy = {}
    lines += ["", "### KV copy (raw bandwidth)", "",
              "| run_id | L | MB | d2h s | h2d s | disk write s | disk read s | cache dropped |",
              "|---|---|---|---|---|---|---|---|"]
    for r in cop:
        for L in sorted({x["length"] for x in r["records"]}):
            rs = [x for x in r["records"] if x["length"] == L]
            c = {k: med(x[k] for x in rs) for k in ("d2h_s", "h2d_s", "disk_write_s", "disk_read_s")}
            copy[L] = c
            lines.append(f"| {r['run_id']} | {L} | {rs[0]['bytes'] / 1e6:.0f} | {fmt(c['d2h_s'])} "
                         f"| {fmt(c['h2d_s'])} | {fmt(c['disk_write_s'], '{:.2f}')} "
                         f"| {fmt(c['disk_read_s'], '{:.2f}')} "
                         f"| {all(x['page_cache_dropped'] for x in rs)} |")
    lines += ["", "### Recompute time / restore time (above 1: restore faster)", "",
              "| L | recompute s | restore from host s | ratio | restore from disk s | ratio |",
              "|---|---|---|---|---|---|"]
    for L in sorted(set(recompute) & set(copy)):
        rc = med(recompute[L])
        host = copy[L]["h2d_s"]
        disk = (copy[L]["disk_read_s"] or 0) + (host or 0)
        lines.append(f"| {L} | {fmt(rc)} | {fmt(host)} | {fmt(rc / host if rc and host else None, '{:.1f}')} "
                     f"| {fmt(disk)} | {fmt(rc / disk if rc and disk else None, '{:.2f}')} |")

    # Phase 4 step 2: KV-sized transfers to a second machine (harness/kv_net_bench.py)
    net = load(a.root, "*_kvnet_*", "records.jsonl")
    if net:
        lines += ["", "### KV copy to a second machine (raw bandwidth)", "",
                  "Total = sender d2h + network + receiver h2d (the time until the standby holds "
                  "the KV cache on its GPU). Ratio = recompute time / total; above 1 means the "
                  "copy would have been faster than recomputing on the standby.", "",
                  "| run_id | streams | part | L | MB | network s | Gbit/s | total s | ratio |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r in net:
            for part in ("sizes-1", "sizes-2"):
                for L in r["lengths"]:
                    rs = [x for x in r["records"] if x["part"] == part and x["length"] == L]
                    if not rs:
                        continue
                    nets = med(x["remote_recv_s"] for x in rs)
                    tot = med(x["d2h_s"] + x["net_and_remote_h2d_s"] for x in rs)
                    rc = med(recompute.get(L, [None]))
                    lines.append(
                        f"| {r['run_id']} | {r['config']['streams']} | {part} | {L} "
                        f"| {rs[0]['bytes'] / 1e6:.0f} | {fmt(nets)} "
                        f"| {fmt(rs[0]['bytes'] * 8 / nets / 1e9 if nets else None, '{:.1f}')} "
                        f"| {fmt(tot)} | {fmt(rc / tot if rc and tot else None, '{:.2f}')} |")
        lines += ["", "Sustained part: Gbit/s of each back-to-back transfer of the largest size, "
                  "in order (a falling sequence means the burst allowance ran out).", ""]
        for r in net:
            seq = [x for x in r["records"] if x["part"] == "sustained"]
            lines.append(f"- {r['run_id']} ({r['config']['streams']} streams): "
                         + ", ".join(f"{x['bytes'] * 8 / x['remote_recv_s'] / 1e9:.1f}" for x in seq))
    text = "\n".join(lines) + "\n"
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
