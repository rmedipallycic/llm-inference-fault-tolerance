"""Paper version 3 tables (Phases 2, 4 and 5), written by analysis/make_tables.py.

Every number comes from the same raw records the per-phase summaries use, through
the per-phase analysis modules, so the paper and the docs cannot disagree:

  paper/tables/tput.tex         Phase 2 follow-up, analysis/throughput.py
  paper/tables/restore.tex      Phase 4, analysis/phase4.py loaders
  paper/tables/sim.tex          Phase 5 Option A, simulation/results.json (SIMULATION)
  paper/tables/p5b_ovh.tex      Phase 5 Option B overhead, analysis/phase5b.py
  paper/tables/p5b_fo.tex       Phase 5 Option B failover, analysis/phase5b.py
  paper/tables/v3_macros.tex    numbers quoted in the text
"""
import json
import os
import statistics
from collections import defaultdict

import phase4
import phase5b
import throughput

HDR = "% generated by analysis/make_tables.py (analysis/v3_tables.py); do not edit by hand\n"
CFG = {("vllm", "default"): "vLLM default", ("vllm", "batch-invariant"): "vLLM batch-invariant",
       ("vllm", "no-apc"): "vLLM no APC", ("sglang", "default"): "SGLang default",
       ("sglang", "deterministic"): "SGLang deterministic"}


def rng(xs, f="{:.0f}"):
    lo, hi = f.format(min(xs)), f.format(max(xs))
    return lo if lo == hi else f"{lo}--{hi}"


def med_rng(xs, f="{:.2f}"):
    xs = [x for x in xs if x is not None]
    return f"{f.format(statistics.median(xs))} ({rng(xs, f)})"


def tput(root, out, mac):
    runs = throughput.load(root)
    if not runs:
        return
    by = defaultdict(list)
    for r in runs:
        by[(r["engine"], r["label"])].append(r)
    base = {}
    rows = []
    for key in CFG:
        if key not in by:
            continue
        reps = sorted(by[key], key=lambda r: r["run_id"])
        levels = {}
        tpot, distinct = [], []
        for r in reps:
            rs, _ = throughput.summarize(r)
            for x in rs:
                levels.setdefault(x["level"], []).append(x["tps"])
                tpot.append(x["tpot"])
            texts = defaultdict(set)
            for q in r["records"]:
                if not q["error"]:
                    texts[q["prompt_id"]].add("".join(c["text"] for c in q["chunks"]))
            distinct.append(rng([len(v) for v in texts.values()]))
        tps = {L: statistics.mean(v) for L, v in levels.items()}
        if key[1] == "default":
            base[key[0]] = tps
        rows.append((key, tps, tpot, distinct))
    with open(os.path.join(out, "tput.tex"), "w", encoding="utf-8") as f:
        f.write(HDR)
        for key, tps, tpot, distinct in rows:
            b = base.get(key[0], {})
            cells = []
            for L in sorted(tps):
                rel = f" ({tps[L] / b[L]:.2f}$\\times$)" if key[1] != "default" and L in b else ""
                cells.append(f"{tps[L]:.0f}{rel}")
            f.write(f"{CFG[key]} & " + " & ".join(cells) + f" & {rng(tpot)} & {' / '.join(distinct)} \\\\\n")
    rel = [tps[L] / base[k[0]][L] for k, tps, _, _ in rows if k[1] in ("batch-invariant", "deterministic")
           for L in tps]
    mac["TputDetMin"], mac["TputDetMax"] = f"{min(rel):.2f}", f"{max(rel):.2f}"
    mac["TputRuns"] = str(len(runs))
    mac["TputRequests"] = str(sum(len(r["records"]) for r in runs))


def restore(root, out, mac):
    pre = phase4.load(root, "*_prefill_*", "requests.jsonl")
    cop = phase4.load(root, "*_kvcopy", "records.jsonl")
    net = phase4.load(root, "*_kvnet_*", "records.jsonl")
    if not (pre and cop):
        return
    rc = defaultdict(list)
    for r in pre:
        for L in r["lengths"]:
            ok = [(x["t_first_mono"] or x["t_end_mono"]) - x["t_start_mono"]
                  for x in r["records"] if x["length"] == L and not x["error"]]
            rc[L].append(statistics.median(ok))
    rc = {L: statistics.median(v) for L, v in rc.items()}
    copy, mb = {}, {}
    for r in cop:
        for L in sorted({x["length"] for x in r["records"]}):
            rs = [x for x in r["records"] if x["length"] == L]
            copy[L] = {k: statistics.median(x[k] for x in rs) for k in ("h2d_s", "disk_read_s")}
            mb[L] = rs[0]["bytes"] / 1e6
    nets = {}
    for r in net:
        s = r["config"]["streams"]
        for L in r["lengths"]:
            rs = [x for x in r["records"] if x["part"] == "sizes-1" and x["length"] == L]
            if rs:
                nets[(s, L)] = statistics.median(x["d2h_s"] + x["net_and_remote_h2d_s"] for x in rs)
    with open(os.path.join(out, "restore.tex"), "w", encoding="utf-8") as f:
        f.write(HDR)
        for L in sorted(set(rc) & set(copy)):
            host = copy[L]["h2d_s"]
            disk = copy[L]["disk_read_s"] + host
            cells = [f"{L:,}".replace(",", "{,}"), f"{mb[L]:,.0f}".replace(",", "{,}"), f"{rc[L]:.3f}",
                     f"{host:.3f} ({rc[L] / host:.1f})", f"{disk:.2f} ({rc[L] / disk:.2f})"]
            for s in (1, 4):
                t = nets.get((s, L))
                cells.append(f"{t:.3f} ({rc[L] / t:.2f})" if t else "--")
            f.write(" & ".join(cells) + " \\\\\n")
    mac["RecompMin"], mac["RecompMax"] = f"{rc[min(rc)]:.2f}", f"{rc[max(rc)]:.1f}"


def sim(out, mac, path=os.path.join("simulation", "results.json")):
    if not os.path.exists(path):
        return
    with open(path, encoding="utf-8") as f:
        rows = json.load(f)["rows"]
    cell = {(r["workload"], r["beta"], r["mtbf_s"], r["policy"]): r for r in rows}
    w, mt = "mixed", 3600
    ff0 = cell[(w, 0.0, mt, "recompute")]["mean_failure_free_T"]
    order = ["recompute", "prompt-only", "fixed-16", "fixed-64", "fixed-256", "fixed-1024",
             "adaptive-proposal", "adaptive-remaining"]
    with open(os.path.join(out, "sim.tex"), "w", encoding="utf-8") as f:
        f.write(HDR)
        for p in order:
            if (w, 0.1, mt, p) not in cell:
                continue
            ovh = [f"{(cell[(w, b, mt, p)]['mean_failure_free_T'] / ff0 - 1) * 100:.2f}"
                   .replace("-", "$-$") for b in (0.1, 0.5, 1.0)]
            c = cell[(w, 0.1, mt, p)]
            f.write(f"{p} & {c['mean_checkpoints']:.1f} & " + " & ".join(ovh)
                    + f" & {c['decode_recovery_mean']:.2f} / {c['decode_recovery_p99']:.2f} \\\\\n")
    mac["SimMixedT"] = f"{ff0:.1f}"
    mac["SimPrefillShare"] = f"{cell[(w, 0.1, mt, 'recompute')]['share_in_prefill'] * 100:.1f}"


def p5b(root, out, mac):
    ov = phase5b.overhead(root)
    if ov:
        base = defaultdict(list)
        for r in ov:
            if r["mode"] == "none":
                base[r["C"]].append(r)
        agg = defaultdict(list)
        for r in ov:
            b = base[r["C"]]
            agg[(r["mode"], r["C"])].append((r["ttft_ms"], r["tpot_ms"],
                                             r["tpot_ms"] / statistics.mean(x["tpot_ms"] for x in b),
                                             r["tps"] / statistics.mean(x["tps"] for x in b)))
        with open(os.path.join(out, "p5b_ovh.tex"), "w", encoding="utf-8") as f:
            f.write(HDR)
            for m in phase5b.MODES:
                c1, c4 = agg.get((m, 1), []), agg.get((m, 4), [])
                if not c1:
                    continue
                f.write(f"{m} & {rng([x[0] for x in c1])} & {rng([x[1] for x in c1], '{:.2f}')} "
                        f"& {rng([x[3] for x in c1], '{:.3f}')} & {rng([x[1] for x in c4], '{:.2f}')} "
                        f"& {rng([x[3] for x in c4], '{:.3f}')} \\\\\n")
    fo = phase5b.failover(root)
    if fo:
        fo = sorted(fo, key=lambda r: (r["L"], phase5b.MODES.index(r["mode"])))
        with open(os.path.join(out, "p5b_fo.tex"), "w", encoding="utf-8") as f:
            f.write(HDR)
            for r in fo:
                mbs = [x for x in r["loaded_mb"] if x is not None]
                f.write(f"{r['L']:,}".replace(",", "{,}") + f" & {r['mode']} & {r['exactly_once']}/{r['trials']} "
                        f"& {med_rng(r['rec'])} & {statistics.median(r['ttft']):.2f} "
                        f"& {f'{statistics.median(mbs):,.0f}'.replace(',', '{,}') if mbs and r['mode'] != 'none' else '--'} "
                        f"& {r['echo']}/{r['trials']} \\\\\n")
        mac["PfbTrials"] = str(sum(r["trials"] for r in fo))
        mac["PfbExactlyOnce"] = str(sum(r["exactly_once"] for r in fo))
        mac["PfbEcho"] = str(sum(r["echo"] for r in fo))
        get = {(r["L"], r["mode"]): r for r in fo}
        for L, tag in ((4096, "Four"), (16384, "Sixteen")):
            for m in phase5b.MODES:
                if (L, m) in get:
                    mac[f"Pfb{tag}{m.capitalize()}"] = f"{statistics.median(get[(L, m)]['rec']):.2f}"
                    mac[f"Pfb{tag}{m.capitalize()}Ttft"] = f"{statistics.median(get[(L, m)]['ttft']):.2f}"


def write(root, out):
    mac = {}
    tput(root, out, mac)
    restore(root, out, mac)
    sim(out, mac)
    p5b(root, out, mac)
    with open(os.path.join(out, "v3_macros.tex"), "w", encoding="utf-8") as f:
        f.write(HDR)
        for k, v in sorted(mac.items()):
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    return mac
