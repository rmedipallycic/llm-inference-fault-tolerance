"""Run the Phase 5 simulation grid and write simulation/results.json and
simulation/summary.md (docs/phase5-plan.md). SIMULATION, not measurement.

  python -m policies.run_sim
"""
import argparse
import json
import os
import subprocess
from functools import partial

from policies import params as PR
from policies import sim

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKLOADS = ("chat", "long", "mixed")
BETAS = (0.0, 0.1, 0.5, 1.0)
MTBF_S = (86400, 3600, 600)
MTBF_NAME = {86400: "1 day", 3600: "1 hour", 600: "10 min"}
BASELINES = ("recompute", "prompt-only", "fixed-16", "fixed-64", "fixed-256", "fixed-1024")
ADAPTIVE = ("adaptive-proposal", "adaptive-remaining")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--requests", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--streams", type=int, default=4)
    ap.add_argument("--out", default=os.path.join(REPO, "simulation"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    p = PR.load(os.path.join(REPO, "experiments"))
    R = partial(PR.recompute_s, p)
    max_ctx = p["r_table"][-1][0]
    reqs = {w: sim.workload(w, a.requests, a.seed, max_ctx) for w in WORKLOADS}
    rows = []
    for w in WORKLOADS:
        for beta in BETAS:
            for mtbf in MTBF_S:
                lam = 1.0 / mtbf
                for name, rule in sim.POLICIES.items():
                    res = sim.evaluate(p, R, reqs[w], rule, lam, beta, a.streams)
                    rows.append({"workload": w, "beta": beta, "mtbf_s": mtbf, "policy": name, **res})
        print(f"done: {w}", flush=True)

    commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                            cwd=REPO).stdout.strip()
    meta = {"kind": "SIMULATION (not measurement); see docs/phase5-plan.md",
            "git_commit": commit, "args": vars(a),
            "measured_inputs": {k: v for k, v in p.items() if k != "sources"},
            "input_runs": p["sources"]}
    with open(os.path.join(a.out, "results.json"), "w", encoding="utf-8") as f:
        json.dump({"meta": meta, "rows": rows}, f, indent=1)
    with open(os.path.join(a.out, "summary.md"), "w", encoding="utf-8") as f:
        f.write(summary(meta, rows, p))
    print(f"wrote {a.out}/results.json and summary.md")


def decide(rows):
    """Apply the plan's decision rule. Returns per-config verdicts."""
    out = []
    keyf = lambda r: (r["workload"], r["beta"], r["mtbf_s"])
    groups = {}
    for r in rows:
        groups.setdefault(keyf(r), {})[r["policy"]] = r
    for key, g in groups.items():
        base_name = min(BASELINES, key=lambda n: g[n]["mean_expected_T"])
        b = g[base_name]
        for an in ADAPTIVE:
            x = g[an]
            dT = (b["mean_expected_T"] - x["mean_expected_T"]) / b["mean_expected_T"]
            dp = (b["recovery_p99"] - x["recovery_p99"]) / b["recovery_p99"]
            win = dT >= 0.05 or (dp >= 0.05 and dT >= -0.001)
            out.append({"workload": key[0], "beta": key[1], "mtbf_s": key[2], "adaptive": an,
                        "baseline": base_name, "dT": dT, "dp99": dp, "win": win})
    return out


def summary(meta, rows, p):
    v = decide(rows)
    go = any(x["win"] for x in v if x["workload"] == "mixed" and x["beta"] in (0.1, 0.5)
             and x["mtbf_s"] >= 3600)
    L = ["# Phase 5 simulation results", "",
         "**SIMULATION, not measurement.** Generated by `python -m policies.run_sim` "
         f"(commit `{meta['git_commit'][:7]}`) from the measured inputs below and the "
         "assumptions in [docs/phase5-plan.md](../docs/phase5-plan.md).", "",
         "## Measured inputs (read from committed logs)", "",
         f"- Recompute R(n): {', '.join(f'{L_}: {r:.3f} s' for L_, r in p['r_table'])}",
         f"- KV bytes per token: {p['kv_bytes']}",
         f"- GPU->host {p['d2h_bw'] / 1e9:.2f} GB/s, host->GPU {p['h2d_bw'] / 1e9:.2f} GB/s",
         f"- Network to the standby: {meta['args']['streams']} streams, "
         f"{p['net_bw'][meta['args']['streams']] * 8 / 1e9:.2f} Gbit/s",
         f"- Time per output token: {p['tpot'] * 1000:.1f} ms",
         f"- Failover detection and switch: {p['detect_s']:.3f} s",
         f"- Input runs: {json.dumps(meta['input_runs'])}", "",
         f"## Decision: {'GO to Option B' if go else 'NO-GO for Option B'}", "",
         "Rule (written before the run): an adaptive policy must win in the mixed workload "
         "for beta 0.1 or 0.5 at a failure rate of 1 hour or rarer. A win is >=5% lower "
         "expected completion time than the best non-adaptive policy for that configuration, "
         "or >=5% lower p99 recovery latency with expected completion time at most 0.1% worse.", "",
         "| workload | beta | MTBF | best non-adaptive | adaptive | dT % | d p99 % | win |",
         "|---|---|---|---|---|---|---|---|"]
    for x in v:
        L.append(f"| {x['workload']} | {x['beta']} | {MTBF_NAME[x['mtbf_s']]} | {x['baseline']} "
                 f"| {x['adaptive']} | {x['dT'] * 100:+.2f} | {x['dp99'] * 100:+.1f} "
                 f"| {'yes' if x['win'] else 'no'} |")
    L += ["", "dT and d p99: improvement over the best non-adaptive policy (positive = adaptive better).",
          "", "## All policies", "",
          "Expected completion time (s, mean per request), failure-free overhead over recompute "
          "(%), p99 recovery latency (s), checkpoints per request.", ""]
    for w in WORKLOADS:
        for mtbf in MTBF_S:
            L += [f"### {w}, MTBF {MTBF_NAME[mtbf]}", "",
                  "| policy | " + " | ".join(f"beta={b}: E[T] / ovh % / p99 / ckpts" for b in BETAS) + " |",
                  "|---|" + "---|" * len(BETAS)]
            for name in sim.POLICIES:
                cells = []
                for b in BETAS:
                    r = next(x for x in rows if x["workload"] == w and x["mtbf_s"] == mtbf
                             and x["beta"] == b and x["policy"] == name)
                    base = next(x for x in rows if x["workload"] == w and x["mtbf_s"] == mtbf
                                and x["beta"] == b and x["policy"] == "recompute")
                    ovh = (r["mean_failure_free_T"] / base["mean_failure_free_T"] - 1) * 100
                    cells.append(f"{r['mean_expected_T']:.3f} / {ovh:.2f} / {r['recovery_p99']:.2f} "
                                 f"/ {r['mean_checkpoints']:.1f}")
                L.append(f"| {name} | " + " | ".join(cells) + " |")
            L.append("")
    L += ["## Supplementary (added after the run): failures during decode only", "",
          "The pre-registered p99 includes failures during prefill, which every policy here "
          "recovers by redoing the prefill. Below, recovery latency for failures after prefill: "
          "mean / p99 (s), at MTBF 1 hour, with the share of failure positions that fall in prefill.", ""]
    for w in WORKLOADS:
        L += [f"### {w}", "", "| policy | " + " | ".join(f"beta={b}" for b in BETAS) + " |",
              "|---|" + "---|" * len(BETAS)]
        for name in sim.POLICIES:
            cells = []
            for b in BETAS:
                r = next(x for x in rows if x["workload"] == w and x["mtbf_s"] == 3600
                         and x["beta"] == b and x["policy"] == name)
                cells.append(f"{r['decode_recovery_mean']:.2f} / {r['decode_recovery_p99']:.2f}")
            L.append(f"| {name} | " + " | ".join(cells) + " |")
        r0 = next(x for x in rows if x["workload"] == w and x["policy"] == "recompute")
        L += ["", f"Share of failure positions in prefill ({w}): {r0['share_in_prefill'] * 100:.1f}%", ""]
    mx = max(r["max_lam_T"] for r in rows)
    L += [f"First-order check: largest failure rate x request duration in the grid = {mx:.3f} "
          "(the approximation assumes this is small).", ""]
    return "\n".join(L)


if __name__ == "__main__":
    main()
